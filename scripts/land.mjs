import { feature } from 'topojson-client';
import { readFileSync, writeFileSync } from 'fs';
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json','utf8'));
const land = feature(topo, topo.objects.land);
const polys = [];
for (const f of land.features) {
  const g = f.geometry;
  const ps = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p of ps) polys.push(p);
}
function inRing(x, y, r) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c; } return c; }
function isLand(lon, lat) { for (const p of polys) { if (inRing(lon, lat, p[0])) { let hole = false; for (let k = 1; k < p.length; k++) if (inRing(lon, lat, p[k])) hole = true; if (!hole) return true; } } return false; }
// fibonacci-ish lat rows with equal spacing on sphere
const pts = [];
const STEP = 1.6;
for (let lat = -84; lat <= 84; lat += STEP) {
  const n = Math.max(1, Math.round(360 / STEP * Math.cos(lat * Math.PI / 180)));
  for (let i = 0; i < n; i++) { const lon = -180 + (i + 0.5) * 360 / n; if (isLand(lon, lat)) pts.push(Math.round(lon * 10) / 10, Math.round(lat * 10) / 10); }
}
writeFileSync('lib/landPoints.ts', `// Generated by scripts/land.mjs from Natural Earth 110m land (world-atlas). [lon, lat, lon, lat, ...]\nexport const LAND_POINTS = new Float32Array(${JSON.stringify(pts)});\n`);
